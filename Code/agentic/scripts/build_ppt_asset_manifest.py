"""Build the 25-page PPT source manifest from runtime and structure assets."""

from __future__ import annotations

import argparse
import json
from datetime import datetime, timezone
from pathlib import Path


PAGE_TITLES = (
    "项目目标", "巡检输入", "火眼视觉证据", "多帧窗口", "质量门控", "标注与数据协议",
    "总体架构", "任务状态机", "Process State Agent", "14维变量分组", "非配对数据治理",
    "F-GMVAE-T", "时序编码器", "JEV路由", "simple_loop", "full_loop并行协作",
    "知识RAG", "特殊案例库", "证据复核", "LLM Gateway", "人工interrupt/resume",
    "审计与报告", "RSI候选演化", "冻结评测与消融", "端到端演示",
)


def build_manifest(root: Path, output: Path) -> dict:
    root = Path(root).resolve()
    runtime = root / "runtime_data"
    assets = root / "report_assets" / "multi_agent_v2"
    demos = sorted(runtime.glob("demo_*.json"))
    images = sorted(item for item in assets.glob("*") if item.suffix.lower() in {".png", ".jpg", ".jpeg", ".webp"})
    source_files = [str(item) for item in demos]
    presentation_demo = runtime / "presentation_demo"
    canonical_demo_files = sorted(item for item in presentation_demo.glob("*.json") if item.name != "index.json") if presentation_demo.exists() else []
    canonical_demo_sources = [str(presentation_demo / "index.json")] + [str(item) for item in canonical_demo_files] if canonical_demo_files else []
    visual_titles = {"巡检输入", "火眼视觉证据", "多帧窗口", "质量门控", "端到端演示"}
    evaluation_titles = {"标注与数据协议", "总体架构", "任务状态机", "Process State Agent", "14维变量分组", "非配对数据治理", "F-GMVAE-T", "时序编码器", "JEV路由", "simple_loop", "full_loop并行协作", "知识RAG", "特殊案例库", "证据复核", "LLM Gateway", "人工interrupt/resume", "审计与报告", "RSI候选演化", "冻结评测与消融"}
    rows = []
    for index, title in enumerate(PAGE_TITLES, start=1):
        structure_image = assets / f"asset-page-{index:02d}.png"
        structure_sidecar = structure_image.with_suffix(".json")
        # Every page must have either a page-specific visual or an explicit
        # source file. The page-specific PNGs are generated by
        # build_ppt_visual_assets.py and are safe structure-validation assets.
        page_sources = []
        if structure_sidecar.exists():
            page_sources.append(str(structure_sidecar))
        if title in visual_titles or title == "项目目标":
            page_sources.extend(canonical_demo_sources or source_files)
        elif title in evaluation_titles and (root / "runtime_data" / "evaluation_report.json").exists():
            page_sources.append(str(root / "runtime_data" / "evaluation_report.json"))
        elif source_files:
            page_sources.append(source_files[0])
        if canonical_demo_sources and title in {"总体架构", "任务状态机", "JEV路由", "simple_loop", "full_loop并行协作", "人工interrupt/resume", "端到端演示"}:
            page_sources.extend(canonical_demo_sources)
        if not page_sources:
            page_sources.append(str(root / "docs" / "PPT演示版快速补全执行清单.md"))

        page_images = [str(structure_image)] if structure_image.exists() else []
        # Keep the real contact sheets as supporting material for input/visual
        # pages, while using one deterministic page asset as the primary image.
        supporting_images = [str(item) for item in images] if title in visual_titles else []
        rows.append({
            "page": index,
            "title": title,
            "source_files": page_sources,
            "image_assets": page_images,
            "supporting_image_assets": supporting_images,
            "status": "flow_validation" if demos else "pending_runtime",
            "claim_policy": "流程验证/实验版本；没有专家视频标签时不写视觉精度",
        })
    payload = {
        "schema_version": "ppt-asset-manifest-1",
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "page_count": len(rows),
        "runtime_demo_count": len(demos),
        "image_asset_count": len(images),
        "pages": rows,
    }
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    return payload


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[2])
    parser.add_argument("--output", type=Path, default=None)
    args = parser.parse_args(argv)
    output = args.output or (args.root / "report_assets" / "multi_agent_v2" / "ppt_asset_manifest.json")
    payload = build_manifest(args.root, output)
    print(json.dumps({"output": str(output), "pages": payload["page_count"], "demos": payload["runtime_demo_count"], "images": payload["image_asset_count"]}, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
